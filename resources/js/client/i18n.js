const readCookie = () => document.cookie.match(/(?:^|;\s*)locale=([^;]+)/)?.[1] ?? null;

export const i18n = reactive({
    locale: ['hu', 'en'].includes(readCookie()) ? readCookie() : (document.documentElement.lang?.slice(0, 2) === 'en' ? 'en' : 'hu'),

    set(locale) {
        this.locale = locale;
        document.cookie = `locale=${locale}; path=/; max-age=31536000; samesite=lax`;
        document.documentElement.lang = locale;
    },
});

export function t(key, params = {}) {
    const text = dictionaries[i18n.locale]?.[key] ?? key;

    return text.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? `{${name}}`));
}
